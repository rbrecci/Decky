import { afterEach, expect, it } from 'vitest';
import { newMatch, seededRng } from '../../supabase/functions/_shared/engine/index.ts';
import { submitActionService, type Rpc } from '../../supabase/functions/_shared/match-service.ts';
import { createTestDb, type TestDb } from './db';
let t:TestDb;
afterEach(async()=>{await t?.db.close();});
it.each([['1v1','player'],['2v2','table']] as const)('integra descoberta, troca, início, espectador e abandono: %s/%s',async(mode,hostMode)=>{
 t=await createTestDb();const host=await t.createUser('Dono');const watcher=await t.createUser('Espectador');
 const count=mode==='1v1'?2:4;const players:string[]=hostMode==='player'?[host]:[];
 while(players.length<count)players.push(await t.createUser('Jogador'+players.length));
 const [room]=await t.asUser<{id:string;code:string}>(host,'select * from public.create_room($1,$2,\'public\')',[hostMode,mode]);
 for(const user of players)if(user!==host||hostMode==='table')await t.asUser(user,'select public.join_room($1)',[room.code]);
 expect(await t.asUser(watcher,'select player_count from public.get_public_rooms()')).toEqual([{player_count:count}]);
 const [swap]=await t.asUser<{id:string}>(players[0],'select * from public.request_seat_swap($1,$2)',[room.id,players[1]]);
 await t.asUser(players[1],'select public.respond_seat_swap($1,true)',[swap.id]);
 const [pending]=await t.asUser<{id:string}>(players[0],'select * from public.request_seat_swap($1,$2)',[room.id,players[1]]);
 for(const user of players)await t.asUser(user,'select public.set_ready($1,true)',[room.id]);
 const game=newMatch(seededRng(22),1,mode);game.public.startsAt=1;
 const [started]=await t.asService<{r:{matchId:string;ok:boolean}}>('select public.internal_start_match($1,$2,$3,$4) as r',[room.id,host,game.public,game.hands]);
 expect(started.r.ok).toBe(true);const matchId=started.r.matchId;
 expect((await t.db.query('select user_id,seat from public.match_players where match_id=$1 order by seat',[matchId])).rows.slice(0,2)).toEqual([{user_id:players[1],seat:1},{user_id:players[0],seat:2}]);
 expect((await t.db.query('select status from public.seat_swap_requests where id=$1',[pending.id])).rows).toEqual([{status:'cancelled'}]);
 expect(await t.asUser(watcher,'select status,match_id from public.get_public_rooms()')).toEqual([{status:'playing',match_id:matchId}]);
 await t.asUser(watcher,'select public.join_spectator($1)',[room.id]);
 const [snapshot]=await t.asUser<{revision:number;public_state:any}>(watcher,'select revision,public_state from public.matches where id=$1',[matchId]);
 expect(snapshot.revision).toBe(0);expect(snapshot.public_state.startsAt).toBeGreaterThan(Date.now());
 expect(await t.asUser(watcher,'select public.get_my_hand($1) as hand',[matchId])).toEqual([{hand:null}]);
 const rpc:Rpc=async(fn,params)=>{
   const entries=Object.entries(params);const args=entries.map(([name],i)=>name+' => $'+(i+1)).join(',');
   const [row]=await t.asService<{r:any}>(`select public.${fn}(${args}) as r`,entries.map(([,value])=>value));return row.r;
 };
 const action={matchId,expectedRevision:0,clientActionId:'antes-inicio',action:{type:'play_card',card:game.hands[0][0]}};
 expect((await submitActionService(rpc,players[1],action,seededRng(2))).body).toEqual({ok:false,error:'too_early'});
 expect((await submitActionService(rpc,watcher,action,seededRng(2))).body).toEqual({ok:false,error:'not_member'});
 await t.db.query("update private.room_presence set last_seen_at=now()-interval '121 seconds'");
 expect(await t.asUser(watcher,'select * from public.get_public_rooms()')).toEqual([]);
 expect(await t.asUser(watcher,'select * from public.matches')).toEqual([]);
 expect((await t.db.query('select room_id,revision,status from public.matches where id=$1',[matchId])).rows).toEqual([{room_id:null,revision:0,status:'playing'}]);
 expect((await t.db.query('select * from public.match_ratings')).rows).toEqual([]);
});
